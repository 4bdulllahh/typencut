// Reads the soundtrack playlist from Spotify's public embed page and writes src/game/playlist.ts.
// Usage: node scripts/playlist.mjs [playlistId]   (re-run after changing the playlist on Spotify)
import { writeFileSync } from "node:fs";

const id = process.argv[2] ?? "0UdsMQsfg58KDNPTKJzBnx";
const html = await (await fetch(`https://open.spotify.com/embed/playlist/${id}`, { headers: { "user-agent": "Mozilla/5.0" } })).text();
const json = html.match(/<script id="__NEXT_DATA__"[^>]*>(.*?)<\/script>/s)?.[1];
if (!json) throw new Error("No track data on the embed page (Spotify changed it?)");
const entity = JSON.parse(json).props.pageProps.state.data.entity;
const tracks = entity.trackList
  .filter((t) => /^spotify:track:[A-Za-z0-9]{22}$/.test(t.uri))
  .map((t) => ({ uri: t.uri, title: t.title.trim(), artist: t.subtitle.replace(/ /g, " ").trim() }));

writeFileSync(
  "src/game/playlist.ts",
  `// Generated by scripts/playlist.mjs from https://open.spotify.com/playlist/${id} ("${entity.name}"). Don't edit by hand.
export const PLAYLIST_ID = ${JSON.stringify(id)};
export const PLAYLIST: { uri: string; title: string; artist: string }[] = ${JSON.stringify(tracks, null, 2)};
`,
);
console.log(`${tracks.length} tracks from "${entity.name}"`);
